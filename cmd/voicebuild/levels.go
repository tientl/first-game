package main

import (
	"bufio"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// matchLevels sets each voice's level (levels, in levelsGo) so it is heard
// as loud as the synthesised voice it replaces: from the game's voice dumps
// before (oldDir) and now (newDir), both made with the same volumes, it
// takes the difference in loudness (the loudest 50 ms) of each sound both
// have, and adds it to the voice's level. A voice with nothing to compare
// with takes its species' mean.
func matchLevels(oldDir, newDir string) error {
	f, err := os.Open(filepath.Join(newDir, "index.txt"))
	if err != nil {
		return err
	}
	defer f.Close()
	// "  0:00.50  rex_roar_1.wav  -4.8 dB  [3 biến thể] rex_roar ×1.00 vol 1.00 — ..."
	line := regexp.MustCompile(`^\s+\S+\s+(\S+_1\.wav)\s+\S+ dB\s+(?:\[\d+ \S+ \S+\] )?(\S+) ×`)
	deltas := map[string][]float64{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := line.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		file, name := m[1], m[2]
		if !slices.ContainsFunc(voices(), func(v voice) bool { return v.name == name }) {
			continue // a synthesised sound still
		}
		if strings.Contains(file, "_herd_") {
			continue // the call again, a little higher
		}
		o, err1 := load(filepath.Join(oldDir, file))
		n, err2 := load(filepath.Join(newDir, file))
		if err1 != nil || err2 != nil {
			continue
		}
		deltas[name] = append(deltas[name], loudness(o)-loudness(n))
	}
	species := map[string][]float64{}
	for v, ds := range deltas {
		sp := v[:strings.IndexByte(v, '_')]
		species[sp] = append(species[sp], mean(ds))
	}
	next := map[string]float64{}
	for _, vc := range voices() {
		d, ok := deltas[vc.name]
		var change float64
		switch {
		case ok:
			change = mean(d)
		case len(species[vc.name[:strings.IndexByte(vc.name, '_')]]) > 0:
			change = mean(species[vc.name[:strings.IndexByte(vc.name, '_')]])
		}
		next[vc.name] = math.Round(max(-9, min(3, levels[vc.name]+change))*10) / 10
	}
	var b strings.Builder
	b.WriteString("package main\n\n// Code generated by \"voicebuild levels\"; DO NOT EDIT.\n\n")
	b.WriteString("// levels is each voice's level in dB, so it is heard as loud as the\n// synthesised voice it replaced (see matchLevels).\nvar levels = map[string]float64{\n")
	names := make([]string, 0, len(next))
	for n := range next {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %.1f,\n", n, next[n])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join("cmd", "voicebuild", "levels_gen.go"), src, 0o644)
}

func mean(xs []float64) float64 {
	s := 0.0
	for _, x := range xs {
		s += x
	}
	return s / float64(max(1, len(xs)))
}

// level scales a mastered voice to its level, never past the peak p.
func level(x []float64, name string, p float64) []float64 {
	g := math.Pow(10, levels[name]/20)
	if m := peakOf(x); m*g > p {
		g = p / m
	}
	return gain(x, g)
}

// loudness is how loud x sounds at its loudest, in dB: the loudest 50 ms
// heard through the ear's weighting (ITU BS.1770's, near enough), which
// cares little for the deepest sounds and much for those around 2–4 kHz.
func loudness(x []float64) float64 {
	k := filter(shelf(x, false, 1500, 4), hp, 60, 0.5, 0)
	return db(loudest(k, 0.05))
}
